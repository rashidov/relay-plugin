#!/bin/sh
# Дежурство Relay: ждём работу и будим агента, когда она пришла.
#
# Программы для этого не нужно. Ожидание — висящий запрос к шине, а текст
# письма собирает она же: нам остаётся отдать его как есть и выйти двойкой.
# Claude Code на двойке будит агента и показывает написанное в stderr.
set -u

# Адрес шины вшит: установка одна, и спрашивать её у человека значит просить
# то, что мы и так знаем. Переменная — только для наших собственных проверок
# на подставной шине.
url="${RELAY_URL:-https://api.relay.rsh-dev.com}"

# Всё состояние дежурства — на каталог проекта, а не на машину.
#
# Одна машина ведёт несколько агентов: в каждом репозитории свой инстанс со
# своими ролями. Пока токен лежал одним файлом на весь дом, второй проект
# затирал первый, и машина умела дежурить ровно за одного.
#
# Имя каталога в имени файла: путь, где косые заменены дефисами. Так же
# делает и сам Claude Code для своих файлов на проект — читается глазами, и
# не нужен ни хэш, ни программа для его подсчёта.
project="${CLAUDE_PROJECT_DIR:-$PWD}"
slug=$(printf '%s' "$project" | tr / -)
home="$HOME/.relay"
token_file="$home/tokens/$slug"

# Токена нет — дежурить нечем, и молчим. Кричать там, где ничего не обещано,
# так же неверно, как молчать там, где обещано.
[ -r "$token_file" ] || exit 0

# Кто дежурит: рабочее место, а не процесс. Хук перезапускается на каждом
# ходе, и отпечаток процесса менялся бы каждый раз — дежурство отказывало бы
# самому себе. Наружу уходит хэш: имя каталога это часто имя проекта и имя
# человека.
holder=$(printf '%s' "$(hostname)|$project" \
  | { shasum -a 256 2>/dev/null || sha256sum 2>/dev/null; } \
  | cut -c1-32)

# Дежурим по одному на проект.
#
# Хук стартует на старте сессии и после каждого хода, а ждёт он теперь в
# цикле — значит к третьему ходу их набралось бы несколько, и все проснулись
# бы на одном письме. Замок каталогом: `mkdir` неделим, и гонки на нём нет.
#
# Замок тоже на проект: общий на машину останавливал бы дежурство соседнего
# репозитория — того самого второго агента, ради которого всё и затевалось.
#
# Мёртвый замок снимаем сами: процесс мог упасть вместе с ноутбуком, и
# дежурство не должно кончаться навсегда из-за оставшейся папки.
# Чья это смена: процесс сессии, который нас запустил.
#
# Хук уходит в фон и живёт сам по себе — а значит переживает свой чат. Живой
# случай 2026-09-10: человек закрыл чат в приложении, хук остался, продолжал
# держать замок и забирать письма В СЕССИЮ, КОТОРОЙ УЖЕ НЕТ. Письмо при этом
# помечается показанным, и вторым разом им никого не разбудить — оно просто
# пропадает. А новый чат поднимал свой хук, тот утыкался в занятый замок и
# молча уходил.
session=$PPID

lock="$home/locks/$slug"
mkdir -p "$home/locks" 2>/dev/null

# Замок держит СЕССИЮ, а не процесс.
#
# Правило простое: дежурство принадлежит тому чату, в котором человек сейчас.
#
# - замок моей же сессии и хук в нём жив — ухожу. Хук стартует после каждого
#   хода, и без этого каждый ход рвал бы ожидание и дёргал шину заново;
# - замок ЧУЖОЙ сессии — забираю. Человек ушёл в другой чат, дежурство идёт
#   за ним. Прежний хук увидит, что замок больше не его, и тихо уйдёт;
# - замок мёртвого — забираю: процесс мог упасть вместе с ноутбуком.
mkdir "$lock" 2>/dev/null

held_pid=$(cat "$lock/pid" 2>/dev/null || echo '')
held_session=$(cat "$lock/session" 2>/dev/null || echo '')

if [ -n "$held_pid" ] && [ "$held_pid" != "$$" ] && kill -0 "$held_pid" 2>/dev/null; then
  if [ "$held_session" = "$session" ]; then
    # Своя же сессия уже дежурит — второй не нужен.
    exit 0
  fi
fi

# Забираем замок себе: и номер процесса, и чья сессия.
echo "$session" > "$lock/session"
echo $$ > "$lock/pid"

# Уходя, убираем за собой — но только если замок всё ещё наш. Иначе снесли бы
# чужое дежурство, которое нас сменило.
trap 'if [ "$(cat "$lock/pid" 2>/dev/null)" = "$$" ]; then rm -rf "$lock" 2>/dev/null; fi' EXIT INT TERM

# Первая пауза после помехи; дальше удваивается до минуты.
pause=1

# Дольше этого не живём: забытый процесс не должен держать дежурство вечно.
# Следующее событие сессии поднимет свежий.
deadline=$(( $(date +%s) + 12 * 60 * 60 ))

# Ждём В ЦИКЛЕ, а не один раз.
#
# Окно ожидания у шины — полторы минуты, и пустое окно это норма, а не конец
# смены. Фоновый хук после выхода сам не перезапускается: новый экземпляр
# стартует только на следующем событии сессии. Значит выход по пустому окну
# означал бы дежурство длиной в полторы минуты — а потом тишину, пока человек
# не заговорит. Ровно та тишина, против которой дежурство и придумано.
while [ "$(date +%s)" -lt "$deadline" ]; do
  # Сессия умерла — уходим и отдаём замок следующему.
  #
  # Проверяем перед каждым заходом, а не однажды: сессия закрывается когда
  # угодно, в том числе пока мы висим в ожидании.
  kill -0 "$session" 2>/dev/null || exit 0

  # Замок забрал кто-то другой — значит человек ушёл в другой чат. Уходим
  # молча: дежурит теперь он, и два ожидания на один инстанс не нужны.
  [ "$(cat "$lock/pid" 2>/dev/null)" = "$$" ] || exit 0

  # Токен уходит через ввод, а не аргументом.
  #
  # `ps` показывает аргументы ВСЕХ процессов машины, и `-H "Bearer …"` клал
  # трёхмесячный ключ на всеобщее обозрение. На ноутбуке это терпимо, а на
  # сервере с постоянным агентом любой процесс прочитал бы чужой доступ.
  # Найдено на живой установке 2026-09-10.
  #
  # `-K -` читает настройки из ввода, а сам заголовок приходит документом
  # ниже: подстановку делает оболочка, и токен не становится аргументом
  # НИ ОДНОЙ команды. Через `printf … | curl` не годится — там он аргумент
  # у `printf`, и тест это поймал.
  out=$(curl -sS -m 100 -K - -X POST "$url/v1/duty/wait" \
    -H 'accept: text/plain' \
    -H 'content-type: application/json' \
    -d "{\"timeout\":90,\"holder\":\"$holder\"}" 2>/dev/null <<RELAY_AUTH
header = "authorization: Bearer $(cat "$token_file")"
RELAY_AUTH
  )
  code=$?

  # Шина не ответила: сеть моргнула, сервис перезапустился. Это пауза, а не
  # конец — ждём и пробуем снова, увеличивая паузу до минуты.
  if [ "$code" -ne 0 ]; then
    sleep "$pause"
    pause=$(( pause * 2 ))
    [ "$pause" -gt 60 ] && pause=60
    continue
  fi

  pause=1

  # Пусто — за окно ничего не пришло. Ждём дальше.
  [ -n "$out" ] || continue

  # Отказ шины приходит JSON-ом: дежурство держит другое рабочее место или
  # доступ отозвали. Повторять бессмысленно — говорим и уходим.
  case "$out" in
    '{"error"'*)
      printf 'Relay: дежурство не поднялось. %s\n' "$out" >&2
      exit 2
      ;;
  esac

  printf '%s\n' "$out" >&2
  exit 2
done

exit 0
